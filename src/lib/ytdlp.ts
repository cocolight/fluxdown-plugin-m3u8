/**
 * 把登录凭据适配成 yt-dlp 能吃的两种形态：`cookies.txt` 与 `--add-header`。
 *
 * ## 为什么不能只写 cookies.txt
 *
 * `authCookie` 设置项接受四种写法（见 `credential.ts`）：bearer / basic / 多行 `Key: Value` /
 * 兜底 Cookie。**只有第四种能变成 Netscape cookies.txt** —— 把 `Bearer abc` 塞进 cookie 行，
 * yt-dlp 会当成一个叫 `Bearer abc` 的 cookie 发出去，站方看到的是垃圾，比不带还糟（凭据泄漏
 * 到一个语义错误的位置，且完全不生效）。
 *
 * 所以这里分两路，各自走 yt-dlp 的原生支持：
 *
 *   - Cookie → 写成 `cookies.txt`，`--cookies <file>`
 *   - 其余头（`Authorization` 等）→ `--add-header "Name: Value"`，一行一个
 *
 * ## 为什么写到 flux.fs
 *
 * `FluxFs` 的注释是权威说明（`types/flux.d.ts`）：
 *
 *   > Per-plugin scratch workspace (same root as the ffmpeg/yt-dlp cwd). Always available.
 *
 * 同一根目录 → yt-dlp 用**相对文件名**就能读到，不用猜绝对路径。写的是 `flux.fs` 而不是
 * ffmpeg 的产物目录，因为后者只在 `onDone` 可见，resolver 阶段根本够不到。
 *
 * ## 纪律
 *
 *   - **每次调用先写后删**：`cookies.txt` 是明文凭据，任务结束立刻删；残留一次就等于把
 *     用户的 Cookie 长期摊在磁盘上。用 `try/finally`，抛错也删。
 *   - **不写就不传**：凭据为空或解析不出 Cookie 时既不写文件也不加 `--cookies`，
 *     绝不用一个空文件覆盖「本来就没凭据」这个事实。
 *   - **文件名固定**：宿主不保证 `flux.fs` 是每次调用独占的，固定名字保证自己能删掉自己
 *     写的那份；并发靠「先写后删」在同一任务内串行（resolver 一次只有一个 yt-dlp 调用）。
 */

import { parseCredential } from "./credential";

/** yt-dlp 读到的相对文件名。固定名，便于清理，也不含需要转义的字符。 */
export const COOKIES_FILE = "cookies.txt";

/** Netscape cookies.txt 的表头。yt-dlp 会校验这一行，缺了会当格式错误。 */
const NETSCAPE_HEADER =
  "# Netscape HTTP Cookie File\n" +
  "# This file is generated by the m3u8-resolver plugin and deleted right after use.\n";

/**
 * Cookie 串 → Netscape cookies.txt 正文。
 *
 * 七个字段按规范排：domain / includeSubdomains / path / secure / expires / name / value。
 *
 * 格式细节已对照 yt-dlp 源码核实（`yt_dlp/cookies.py` 的 `YoutubeDLCookieJar.load()`）：
 *
 *   - **必须 Tab 分隔且恰好 7 列**。源码 `line.split('\t')` 后校验 `len == 7`，多一列少
 *     一列都抛 `LoadError`，该行被**静默跳过**。所以这里显式剔除名字/值里的 `\t\r\n`。
 *   - **`expires = 0` 是会话 cookie**。CPython 的 `MozillaCookieJar` 只认空串，yt-dlp
 *     在 `load()` 末尾显式把 `0` 转成 `None` + `discard=True`。我们拿不到真实过期时间
 *     （设置项里只有 `name=value`），用 0 最诚实。
 *   - **`includeSubdomains` 列在读取时其实不参与解析**，底层只看 domain 的**前导点**：
 *     带点才算含子域。这里两者保持一致（都带点、都 TRUE），免得写出自相矛盾的行。
 *   - **文件头不强制**。`#` 开头的行一律当注释，只有 `#HttpOnly_` 是特殊前缀。我们写
 *     标准头只是为了让文件能被人看懂，去掉也不影响加载。
 *
 * `secure` 由调用方按 URL scheme 决定，**不在这里写死**：见 `toNetscapeCookies` 的
 * `secure` 参数说明。
 *
 * @param cookie `name=value; name2=value2` 形态的串，可含空白
 * @param host 凭据归属站点的主机名（不含 scheme / 端口 / 路径）
 * @param secure 是否只发给 HTTPS。`true` → 该 cookie 仅 HTTPS 发送
 * @returns 正文；没有可用键值对时返回空串（调用方据此决定不写文件）
 */
export function toNetscapeCookies(
  cookie: string | null | undefined,
  host: string,
  secure: boolean,
): string {
  const text = String(cookie == null ? "" : cookie).trim();
  const h = String(host == null ? "" : host)
    .trim()
    .toLowerCase();
  // 主机名只保留合法的 DNS 字符；为空则无法构造行，直接放弃（宁可不带，也不写坏文件）。
  if (!text || !h) return "";
  if (!/^[a-z0-9.-]+$/.test(h)) return "";

  const domain = h.charAt(0) === "." ? h : "." + h;
  // secure 列必须与 URL scheme 一致：写死 TRUE 会让 HTTP 站点的 cookie 一条都不发出去
  // （底层解析成 `secure=True` 即「只走 HTTPS」），表现是凭据注入成功但站点仍说未登录。
  const secureFlag = secure ? "TRUE" : "FALSE";
  const lines: string[] = [];
  const parts = text.split(";");
  for (let i = 0; i < parts.length; i++) {
    const seg = parts[i].trim();
    if (!seg) continue;
    const eq = seg.indexOf("=");
    // 无 `=` 的段（如属性残留）不是 cookie，跳过；name 为空的也跳过。
    if (eq <= 0) continue;
    const name = seg.slice(0, eq).trim();
    const value = seg.slice(eq + 1).trim();
    if (!name) continue;
    // 字段里的制表符/换行会破坏一行七列的格式，直接剔除。
    const cleanName = name.replace(/[\t\r\n]/g, "");
    const cleanValue = value.replace(/[\t\r\n]/g, "");
    if (!cleanName) continue;
    lines.push([domain, "TRUE", "/", secureFlag, "0", cleanName, cleanValue].join("\t"));
  }
  if (!lines.length) return "";
  return NETSCAPE_HEADER + lines.join("\n") + "\n";
}

/**
 * 凭据文本 → yt-dlp 参数（不含 `cookies.txt` 的写入，那部分要 IO）。
 *
 * 返回 `addHeaders` 是可以直接拼进 `args` 的成对参数（`["--add-header", "K: V", ...]`），
 * 以及 `cookie`（原始 Cookie 值，写文件的正文由调用方转 Netscape 格式）。
 *
 * `Cookie` 头单独拎出来，是因为它要走 `--cookies` 而不是 `--add-header`：yt-dlp 对
 * `--add-header "Cookie: ..."` 的支持在旧版本里不稳（部分站点会被 Cloudflare 之类拦下），
 * 而 `--cookies` 是它一等公民的能力，还能让站点的 `Set-Cookie` 回归文件。
 */
export function ytdlpArgsFromCredential(
  raw: string | null | undefined,
  origin: string,
): { cookie: string; addHeaders: string[] } {
  const empty = { cookie: "", addHeaders: [] as string[] };
  const cred = parseCredential(raw, origin);
  if (!cred) return empty;

  const addHeaders: string[] = [];
  let cookie = "";
  const keys = Object.keys(cred.headers);
  for (let i = 0; i < keys.length; i++) {
    const k = keys[i];
    const v = cred.headers[k];
    if (!v) continue;
    if (k.toLowerCase() === "cookie") cookie = v;
    else addHeaders.push("--add-header", k + ": " + v);
  }
  return { cookie, addHeaders };
}
